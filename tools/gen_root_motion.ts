// Generates scripts/player/root_motion_tracks.gd from the original's
// first-person animation data, extracted into the untracked research folder.
//
//   bun tools/gen_root_motion.ts <me-re anims dir>
//   e.g. bun tools/gen_root_motion.ts ../../_local/me-re/anims
//
// What is written is only what the move logic needs: each sequence's 1P length
// and, for the sequences a move plays with root motion, the root bone's
// trajectory in the actor frame the anim started in (forward, right, up cm,
// yaw degrees turning right), one key per 1/30 s. Never bone poses: the
// original's rest pose is not this project's, and the model plays its own
// clips.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("usage: bun tools/gen_root_motion.ts <me-re anims dir>");

// The moves whose animation lengths are read: the ledge family.
const MOVES = [
  "TdMove_SpeedVault", "TdMove_AutoStepUp", "TdMove_StepUp", "TdMove_IntoGrab",
  "TdMove_Grab", "TdMove_GrabPullUp", "TdMove_GrabJump", "TdMove_GrabTransfer",
  "TdMove_IntoClimb", "TdMove_Climb", "TdMove_LedgeWalk", "TdMove_Balance",
];

// The sequences played with root motion (UseRootMotion true while they run).
const TRACKED = [
  "HangFoldedHeaveUp", "hangfreeheaveuptocrouch", "HangFreeHeaveUp", "HangHeaveUpToCrouch",
  "HangHeaveUp", "HangFreeHeaveOver", "HangHeaveOver",
  "HangCornerOutSideLeft", "HangCornerOutSideRight", "HangFreeCornerOutSideLeft",
  "HangFreeCornerOutSideRight",
  "LadderExitTopRightHand", "LadderExitTopLeftHand", "pipeexittoprighthand", "pipeexittoplefthand",
  "LadderEnterTop", "walkbalancefalloffleft", "walkbalancefalloffright",
  "stepupleftleg48", "stepuprightleg48", "stepupleftleg88", "stepuprightleg88", "stepup144",
];

const md = readFileSync(join(dir, "moves_to_anims.md"), "utf8");
const lengths = new Map<string, number>();
let inMove = false;
for (const line of md.split("\n")) {
  if (line.startsWith("### ")) {
    inMove = MOVES.includes(line.slice(4).trim());
    continue;
  }
  if (!inMove || !line.startsWith("| ") || line.startsWith("| anim") || line.startsWith("|---")) continue;
  const cells = line.split("|").map((c) => c.trim());
  const name = cells[1].replace(/\s*\*\*.*$/, "");
  const len = parseFloat(cells[7]);
  if (!name || Number.isNaN(len)) continue;
  lengths.set(name.toLowerCase(), len);
}

const fmt = (x: number) => (Math.round(x * 1000) / 1000).toString();
let tracks = "";
for (const name of TRACKED) {
  const j = JSON.parse(readFileSync(join(dir, "root_motion", `${name}.json`), "utf8"));
  const a = j.by_anim_set.AS_C1P_Unarmed;
  const samples: { t: number; delta: number[]; roll_pitch_yaw_deg: number[] }[] = a.samples;
  const keys: string[] = [];
  const step = 1 / 30;
  for (let t = 0; t < a.SequenceLength + step * 0.5; t += step) {
    const tt = Math.min(t, a.SequenceLength);
    let i = 0;
    while (i < samples.length - 2 && samples[i + 1].t < tt) i++;
    const s0 = samples[i];
    const s1 = samples[i + 1];
    const k = s1.t > s0.t ? Math.min(Math.max((tt - s0.t) / (s1.t - s0.t), 0), 1) : 0;
    const lerp = (p: number, q: number) => p + (q - p) * k;
    const d = [0, 1, 2].map((c) => lerp(s0.delta[c], s1.delta[c]));
    let y0 = s0.roll_pitch_yaw_deg[2];
    let y1 = s1.roll_pitch_yaw_deg[2];
    if (y1 - y0 > 180) y1 -= 360;
    if (y0 - y1 > 180) y1 += 360;
    keys.push(`${fmt(d[0])}, ${fmt(d[1])}, ${fmt(d[2])}, ${fmt(lerp(y0, y1))}`);
  }
  lengths.set(name.toLowerCase(), a.SequenceLength);
  tracks += `\t&"${name.toLowerCase()}": [\n\t\t${keys.join(",\n\t\t")}],\n`;
}

let lens = "";
for (const [name, len] of [...lengths.entries()].sort()) lens += `\t&"${name}": ${Math.round(len * 1e5) / 1e5},\n`;

const out = `class_name RootMotionTracks
extends RefCounted

# GENERATED by tools/gen_root_motion.ts from the original's first-person
# animation data. DO NOT edit by hand: change the generator and re-run it.
#
# [ME:CONFIRMED anims/moves_to_anims.md, anims/root_motion] LENGTHS are
# SequenceLength at rate 1 of the AS_C1P_Unarmed sequence, keyed by the
# lowercased name (the original's names are case-insensitive). TRACKS are the
# root bone's trajectory for the sequences a move plays with root motion:
# per key (one every 1/30 s from 0 to the length, the last clamped to it)
# forward, right, up in cm and yaw in degrees turning right, relative to where
# the root was at 0 and in the actor frame the sequence started in.
# RootMotionClip.from_track() reads them.

const KEY_STEP := 1.0 / 30.0

const LENGTHS := {
${lens}}

const TRACKS := {
${tracks}}
`;
writeFileSync("scripts/player/root_motion_tracks.gd", out);
console.log(`${lengths.size} lengths, ${TRACKED.length} tracks`);
